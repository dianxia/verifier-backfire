# -*- coding: utf-8 -*-
"""Truly paired feedback ablation (E3-paired).

For every task whose oracle_full FIRST attempt (from the fresh rerun
logs) was wrong, re-run the repair sub-loop twice from that exact same
starting code -- once with verdict-only feedback, once with the full
test traceback.  Generator, temperature, budget (rounds 2..N) and the
unit-test oracle are identical; feedback content is the only
difference.  Repair outcomes are paired per task and tested with exact
McNemar.

The seed's initial traceback is regenerated by re-running the oracle
on the shared starting code, so both variants see byte-identical
feedback of their own kind.

Usage:
    python -m src.paired_e3 --path results/e1.jsonl \
        [--data data/humaneval.jsonl] [--out results/e3_paired_e1.jsonl] \
        [--threads 8]
"""
import argparse
import ast
import json
import math
import os
import threading
import time
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor, as_completed

from .llm import chat
from .loop import (BUDGET, GEN_MAX_TOKENS, GEN_MODEL, GEN_TEMPERATURE,
                   _gen_messages)
from .sandbox import extract_code, run_oracle

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_DATA = os.path.join(_ROOT, "data", "humaneval.jsonl")


def mcnemar_exact(b: int, c: int) -> float:
    """Two-sided exact McNemar p-value."""
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    p = 2.0 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n
    return min(p, 1.0)


def load_records(path: str) -> list[dict]:
    recs = []
    try:
        with open(path, encoding="utf-8") as f:
            for line in f:
                try:
                    recs.append(json.loads(line))
                except json.JSONDecodeError:
                    pass
    except FileNotFoundError:
        pass
    return recs


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--path", required=True,
                    help="rerun log to take oracle_full seeds from")
    ap.add_argument("--data", default=DEFAULT_DATA)
    ap.add_argument("--out", required=True)
    ap.add_argument("--threads", type=int, default=8)
    args = ap.parse_args()

    tasks = {}
    with open(args.data, encoding="utf-8") as f:
        for line in f:
            t = json.loads(line)
            tasks[t["task_id"]] = t

    # seeds: oracle_full first attempts that were wrong
    seeds = []
    for r in load_records(args.path):
        if r.get("arm") != "oracle_full" or "error" in r:
            continue
        if not r["attempts"]:
            continue
        a0 = r["attempts"][0]
        if a0["gt_pass"]:
            continue
        seeds.append({"task_id": r["task_id"], "code0": a0["code"]})
    print(f"paired E3 seeds: {len(seeds)} wrong-first attempts "
          f"(oracle_full, from {args.path})", flush=True)
    if not seeds:
        print("nothing to do", flush=True)
        return

    def feedback_for(mode: str, output: str) -> str:
        if mode == "verdict":
            return "Your solution failed the tests."
        return ("Your solution failed the tests. The test harness "
                f"produced the following error:\n{output[-1200:]}")

    def run_variant(seed: dict, mode: str) -> dict:
        task = tasks[seed["task_id"]]
        # regenerate the shared initial failure output so both
        # variants get byte-identical feedback of their own kind
        _, out0 = run_oracle(seed["code0"], task["test"],
                             task["entry_point"])
        prev_code = seed["code0"]
        fb = feedback_for(mode, out0)
        attempts = []
        gen_model_api_id = None
        resolved = False
        for k in range(2, BUDGET + 1):
            text, gu = chat(
                GEN_MODEL, _gen_messages(task, k, prev_code, fb),
                max_tokens=GEN_MAX_TOKENS, temperature=GEN_TEMPERATURE,
            )
            if gen_model_api_id is None:
                gen_model_api_id = gu.get("model")
            code = extract_code(text, task["entry_point"])
            passed, output = run_oracle(
                code, task["test"], task["entry_point"])
            try:
                ast.parse(code)
                parse_ok = True
            except Exception:  # noqa: BLE001
                parse_ok = False
            attempts.append({
                "k": k,
                "code": code,
                "gt_pass": passed,
                "gt_out": output[:500],
                "parse_ok": parse_ok,
                "gen_tokens": gu.get("total_tokens", 0),
                "gen_prompt_tokens": gu.get("prompt_tokens", 0),
                "gen_completion_tokens": gu.get("completion_tokens", 0),
            })
            if passed:
                resolved = True
                break
            prev_code = code
            fb = feedback_for(mode, output)
        return {
            "task_id": seed["task_id"],
            "mode": mode,
            "gen_model_api_id": gen_model_api_id,
            "n_attempts": len(attempts),
            "resolved": resolved,
            "delivered_correct": bool(resolved),
            "attempts": attempts,
        }

    # resume: skip (task_id, mode) pairs already in the output file
    done = {(r["task_id"], r["mode"]) for r in load_records(args.out)
            if "error" not in r}
    jobs = [(s, m) for s in seeds for m in ("verdict", "full")
            if (s["task_id"], m) not in done]
    print(f"jobs={len(jobs)} (skipped {len(done)} done)", flush=True)

    lock = threading.Lock()
    counter = {"n": 0, "err": 0}
    t0 = time.time()
    with open(args.out, "a", encoding="utf-8") as out:
        with ThreadPoolExecutor(max_workers=args.threads) as ex:
            futs = {ex.submit(run_variant, s, m): (s, m)
                    for s, m in jobs}
            for fut in as_completed(futs):
                s, m = futs[fut]
                try:
                    rec = fut.result()
                except Exception as e:  # noqa: BLE001
                    counter["err"] += 1
                    out.write(json.dumps({
                        "task_id": s["task_id"], "mode": m,
                        "error": repr(e)[:500],
                    }, ensure_ascii=False) + "\n")
                    out.flush()
                    print(f"variant failed: {s['task_id']}/{m}: {e}",
                          flush=True)
                    continue
                with lock:
                    out.write(json.dumps(rec, ensure_ascii=False) + "\n")
                    out.flush()
                    counter["n"] += 1
                    if counter["n"] % 10 == 0:
                        el = time.time() - t0
                        print(f"[{counter['n']}/{len(jobs)}] "
                              f"{el:.0f}s elapsed", flush=True)
    print(f"done: {counter['n']} ok, {counter['err']} errors",
          flush=True)

    # ---- paired analysis (complete pairs only) ----
    by_task = defaultdict(dict)
    for r in load_records(args.out):
        if "error" not in r and "delivered_correct" in r:
            by_task[r["task_id"]][r["mode"]] = bool(
                r["delivered_correct"])
    b = c = v_n = f_n = n_pairs = 0
    for modes in by_task.values():
        if "verdict" not in modes or "full" not in modes:
            continue
        n_pairs += 1
        v, fl = modes["verdict"], modes["full"]
        v_n += v
        f_n += fl
        if v and not fl:
            b += 1
        elif fl and not v:
            c += 1
    print(f"\npaired repair success: verdict-only {v_n}/{n_pairs}, "
          f"traceback {f_n}/{n_pairs}", flush=True)
    print(f"discordant: verdict-only-wins={b}, traceback-wins={c}, "
          f"McNemar exact p={mcnemar_exact(b, c):.4f}", flush=True)


if __name__ == "__main__":
    main()